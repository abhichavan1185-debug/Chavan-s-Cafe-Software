export const matchCategory = (itemCat: string, targetCat: string): boolean => {
  if (targetCat === "All") return true;
  if (itemCat === targetCat) return true;
  const ic = itemCat.toLowerCase();
  const tc = targetCat.toLowerCase();
  if (tc === "coffee" && (ic.includes("coffee") || ic.includes("hot beverages"))) return true;
  if (tc === "tea" && (ic.includes("tea") || ic.includes("chai"))) return true;
  if (tc === "burgers" && (ic.includes("burger") || ic.includes("sandwich"))) return true;
  if (tc === "chinese" && (ic.includes("chinese") || ic.includes("manchurian") || ic.includes("noodles") || ic.includes("momos"))) return true;
  if (tc === "noodles" && (ic.includes("noodle") || ic.includes("maggi") || ic.includes("chinese"))) return true;
  if (tc === "manchurian" && (ic.includes("manchurian") || ic.includes("chinese"))) return true;
  if (tc === "momos" && ic.includes("momo")) return true;
  if (tc === "cakes" && (ic.includes("cake") || ic.includes("bakery") || ic.includes("pastr"))) return true;
  if (tc === "snacks" && (ic.includes("fries") || ic.includes("rolls") || ic.includes("maggi") || ic.includes("snack") || ic.includes("bakery"))) return true;
  if (tc === "fast food" && (ic.includes("pizza") || ic.includes("burger") || ic.includes("fries") || ic.includes("rolls"))) return true;
  if (tc === "veg food" && ic.includes("veg") && !ic.includes("non-veg")) return true;
  if (tc === "non-veg food" && ic.includes("non-veg")) return true;
  return ic.includes(tc);
};


